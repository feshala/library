export const akuTranslations = (() => {
  const flat = {};
  Object.values(akuTranslationsByRegion).forEach((continent) => {
    Object.values(continent).forEach((country) => {
      Object.entries(country).forEach(([code, data]) => {
        if (!flat[code]) flat[code] = data;
      });
    });
  });
  return flat;
})();

export function translateAku(lang = "en") {
  const item = akuTranslations[lang];
  if (!item) {
    throw new Error(`Bahasa dengan kode "${lang}" tidak ditemukan.`);
  }
  return item.translation;
}

export function getAkuByRegion(continent, country, lang) {
  const c = akuTranslationsByRegion[continent];
  if (!c) throw new Error(`Benua "${continent}" tidak ditemukan.`);
  const n = c[country];
  if (!n) throw new Error(`Negara "${country}" tidak ditemukan di benua "${continent}".`);
  const item = n[lang];
  if (!item) throw new Error(`Bahasa "${lang}" tidak ditemukan di "${country}".`);
  return item.translation;
}

export default akuTranslationsByRegion;
